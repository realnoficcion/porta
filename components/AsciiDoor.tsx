export function AsciiDoor() {
  const [i, setI] = useState(0);

  useEffect(() => {
    const id = window.setInterval(() => {
      setI((n) => (n + 1) % FRAMES.length);
    }, 260);
    return () => window.clearInterval(id);
  }, []);

  return (
    <pre
      aria-hidden
      className="font-mono text-bone leading-[1] whitespace-pre select-none"
      style={{
        fontSize: "clamp(10px, 1.3vw, 18px)",
        letterSpacing: "0",
        textShadow: "0 0 20px rgba(0,0,0,0.6)",
      }}
    >
      {FRAMES[i]}
    </pre>
  );
}
